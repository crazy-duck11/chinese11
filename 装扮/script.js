function loadSavedLooks() {
  try {
    const value = JSON.parse(localStorage.getItem("yijianSavedLooks") || "[]");
    return Array.isArray(value) ? value : [];
  } catch (error) {
    console.warn("无法读取本地造型记录：", error);
    return [];
  }
}

function persistSavedLooks() {
  try {
    localStorage.setItem("yijianSavedLooks", JSON.stringify(savedLooks));
    return true;
  } catch (error) {
    console.error("保存造型失败：", error);
    showToast("浏览器存储失败，请检查浏览器设置或存储空间");
    return false;
  }
}

function showToast(message) {
  const toast = $("#toast");
  toast.textContent = message;
  toast.classList.add("show");

  clearTimeout(toastTimer);
  toastTimer = setTimeout(() => {
    toast.classList.remove("show");
  }, 2400);
}

function getCurrentItems() {
  return ethnicData[currentEthnic].items[currentCategory] || [];
}

function getAllSelectedItems() {
  return categoryNames
    .map(category => {
      const id = selections[category];
      const item = ethnicData[currentEthnic].items[category]
        .find(entry => entry.id === id);

      return item ? { ...item, category } : null;
    })
    .filter(Boolean);
}

function getSelectedItemsForLook(look) {
  if (!look || !look.selections) return [];

  return categoryNames
    .map(category => {
      const itemId = look.selections[category];
      const item = ethnicData[look.ethnic]?.items[category]
        ?.find(entry => entry.id === itemId);

      return item ? { ...item, category } : null;
    })
    .filter(Boolean);
}

function renderEthnicList() {
  $$(".ethnic-option").forEach(button => {
    const active = button.dataset.ethnic === currentEthnic;
    button.classList.toggle("active", active);
    button.setAttribute("aria-pressed", String(active));
  });
}

